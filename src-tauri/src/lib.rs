#[tauri::command]
fn load_snippets(app: tauri::AppHandle) -> Vec<Snippet> {
    read_json(&data_path(&app))
}

#[tauri::command]
fn save_snippets(app: tauri::AppHandle, snippets: Vec<Snippet>) {
    let _ = write_json_atomic(&data_path(&app), &snippets);
}

#[tauri::command]
fn get_data_path(app: tauri::AppHandle) -> String {
    // The containing folder, not just snippets.json, so the UI can honestly show
    // where the clipboard log lives too.
    ensure_data_dir(&app).to_string_lossy().to_string()
}

#[tauri::command]
fn write_clipboard(state: tauri::State<'_, AppState>, text: String) -> bool {
    // An explicit user Copy: put it on the pasteboard normally (do not exclude
    // it from other clipboard managers — the user asked for this value to be
    // available), and mark it so our own watcher doesn't re-record it.
    if set_clipboard_plain(&text) {
        *state.skip_text.lock().unwrap() = Some(text);
        true
    } else {
        false
    }
}

#[tauri::command]
fn load_clipboard_history(app: tauri::AppHandle) -> Vec<ClipboardEntry> {
    read_json(&history_path(&app))
}

#[tauri::command]
fn get_settings(app: tauri::AppHandle) -> Settings {
    let settings = load_settings(&app);
    // Keep AppState in sync with disk so the watcher and the UI can't drift.
    if let Some(state) = app.try_state::<AppState>() {
        *state.history_limit.lock().unwrap() = settings.history_limit;
        *state.recording_enabled.lock().unwrap() = settings.enabled;
    }
    settings
}

#[tauri::command]
fn save_settings_cmd(app: tauri::AppHandle, settings: Settings) {
    let _ = write_json_atomic(&settings_path(&app), &settings);
    if let Some(state) = app.try_state::<AppState>() {
        *state.history_limit.lock().unwrap() = settings.history_limit;
        *state.recording_enabled.lock().unwrap() = settings.enabled;
        *state.snippets_dir.lock().unwrap() =
            settings.snippets_dir.as_ref().map(PathBuf::from);
    }
}

#[tauri::command]
fn toggle_pin(state: tauri::State<'_, AppState>, app: tauri::AppHandle, id: String) -> bool {
    let (snapshot, pinned) = {
        let mut history = state.clipboard_history.lock().unwrap();
        let mut pinned = false;
        if let Some(e) = history.iter_mut().find(|e| e.id == id) {
            e.pinned = !e.pinned;
            pinned = e.pinned;
        }
        (history.clone(), pinned)
    };
    let _ = write_json_atomic(&history_path(&app), &snapshot);
    pinned
}

#[tauri::command]
fn clear_clipboard_history(state: tauri::State<'_, AppState>, app: tauri::AppHandle) {
    state.clipboard_history.lock().unwrap().clear();
    // Reset the dedupe key so re-copying the just-cleared text records again.
    *state.last_clipboard.lock().unwrap() = String::new();
    let _ = write_json_atomic(&history_path(&app), &Vec::<ClipboardEntry>::new());
}

#[tauri::command]
fn pin_to_snippets(app: tauri::AppHandle, content: String) -> Snippet {
    let mut snippets = load_snippets(app.clone());

    let now = now_millis();
    let preview: String = content.chars().take(50).collect();
    let title = if preview.chars().count() < content.chars().count() {
        preview + "..."
    } else {
        preview
    };
    let snippet = Snippet {
        id: next_id(),
        title,
        content,
        tag: String::new(),
        created: now,
        updated: now,
        uses: 0,
        last_used: 0,
    };

    snippets.insert(0, snippet.clone());
    save_snippets(app, snippets);
    snippet
}

#[tauri::command]
fn open_url(url: String) {
    // Only http(s) — never hand an arbitrary scheme or file path from clipboard
    // content to `open`.
    if url.starts_with("http://") || url.starts_with("https://") {
        let _ = std::process::Command::new("open").arg(&url).spawn();
    }
}

#[tauri::command]
fn reveal_path(path: String) {
    let _ = std::process::Command::new("open").arg("-R").arg(&path).spawn();
}

// Point the snippet store at a folder (e.g. iCloud Drive) or back to local
// (None). Returns the effective snippet list: an existing file in the target
// wins (adopting already-synced snippets); otherwise the current set seeds it.
#[tauri::command]
fn set_snippets_dir(
    app: tauri::AppHandle,
    state: tauri::State<'_, AppState>,
    dir: Option<String>,
) -> Vec<Snippet> {
    let current = load_snippets(app.clone());
    let mut settings = load_settings(&app);
    settings.snippets_dir = dir.clone();
    let _ = write_json_atomic(&settings_path(&app), &settings);
    *state.snippets_dir.lock().unwrap() = dir.as_ref().map(PathBuf::from);

    let new_path = data_path(&app);
    if new_path.exists() {
        read_json(&new_path)
    } else {
        let _ = write_json_atomic(&new_path, &current);
        current
    }
}

#[tauri::command]
fn get_snippets_dir(app: tauri::AppHandle) -> Option<String> {
    load_settings(&app).snippets_dir
}

#[tauri::command]
fn export_snippets_to(app: tauri::AppHandle, path: String) -> bool {
    let snippets = load_snippets(app.clone());
    match serde_json::to_string_pretty(&snippets) {
        Ok(json) => fs::write(&path, json).is_ok(),
        Err(_) => false,
    }
}

#[tauri::command]
fn import_snippets_from(path: String) -> Vec<Snippet> {
    match fs::read_to_string(&path) {
        Ok(data) => serde_json::from_str(&data).unwrap_or_default(),
        Err(_) => Vec::new(),
    }
}

// Open-at-login. The launch agent the plugin writes is the source of truth —
// deliberately not mirrored into settings.json, which would only give the two
// a chance to disagree after the user removes the item in System Settings.
#[tauri::command]
fn get_autostart(app: tauri::AppHandle) -> bool {
    use tauri_plugin_autostart::ManagerExt;
    app.autolaunch().is_enabled().unwrap_or(false)
}

// Returns the state that actually took effect, so a failed write shows up in
// the UI as the switch springing back rather than a lie that sticks.
#[tauri::command]
fn set_autostart(app: tauri::AppHandle, enabled: bool) -> bool {
    use tauri_plugin_autostart::ManagerExt;
    let manager = app.autolaunch();
    let _ = if enabled {
        manager.enable()
    } else {
        manager.disable()
    };
    manager.is_enabled().unwrap_or(false)
}

#[tauri::command(async)]
fn paste_and_hide(app: tauri::AppHandle, state: tauri::State<'_, AppState>, text: String) -> bool {
    // Without Accessibility permission CGEvent posting silently no-ops. Report
    // that honestly so the UI can prompt, instead of claiming success.
    #[cfg(target_os = "macos")]
    if !accessibility_trusted() {
        return false;
    }

    // Transient transport for the synthetic paste — mark it so other clipboard
    // managers on the machine don't also capture the secret.
    if !set_clipboard_excluded(&text) {
        return false;
    }
    *state.skip_text.lock().unwrap() = Some(text);

    if let Some(window) = app.get_webview_window("main") {
        hide_panel(&window);
    }

    // Give macOS time to restore focus to the previously-frontmost app before
    // the keystroke lands. Runs on an async command worker, so it does not block
    // the main/UI thread.
    std::thread::sleep(Duration::from_millis(350));

    simulate_paste()
}

