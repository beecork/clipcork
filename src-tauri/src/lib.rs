#[derive(Serialize, Deserialize, Clone)]
struct Settings {
    #[serde(default = "default_limit")]
    history_limit: usize,
    // Whether clipboard recording is active. `#[serde(default)]` so upgrading an
    // existing settings.json (which predates this field) keeps recording on
    // rather than silently resetting every field to Default.
    #[serde(default = "default_enabled")]
    enabled: bool,
    // Optional folder (e.g. inside iCloud Drive / Dropbox) to store snippets.json
    // in, so a personal snippet library syncs across Macs. History and settings
    // always stay in the local app-data dir.
    #[serde(default)]
    snippets_dir: Option<String>,
}

fn default_limit() -> usize {
    20
}

fn default_enabled() -> bool {
    true
}

impl Default for Settings {
    fn default() -> Self {
        Self {
            history_limit: default_limit(),
            enabled: default_enabled(),
            snippets_dir: None,
        }
    }
}

fn load_settings(app: &tauri::AppHandle) -> Settings {
    let path = settings_path(app);
    if path.exists() {
        read_json(&path)
    } else {
        let s = Settings::default();
        let _ = write_json_atomic(&path, &s);
        s
    }
}

