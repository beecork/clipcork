static DATA_DIR: OnceLock<PathBuf> = OnceLock::new();

// Resolved once and cached — this is on the clipboard-capture hot path, so it
// must not re-run `app_data_dir()` + two syscalls on every write.
fn ensure_data_dir(app: &tauri::AppHandle) -> PathBuf {
    DATA_DIR
        .get_or_init(|| {
            let dir = app
                .path()
                .app_data_dir()
                .unwrap_or_else(|_| std::env::temp_dir().join("clipcork"));
            let _ = fs::create_dir_all(&dir);
            #[cfg(unix)]
            {
                let _ = fs::set_permissions(&dir, fs::Permissions::from_mode(0o700));
            }
            dir
        })
        .clone()
}

fn app_file(app: &tauri::AppHandle, name: &str) -> PathBuf {
    ensure_data_dir(app).join(name)
}

fn data_path(app: &tauri::AppHandle) -> PathBuf {
    // Snippets may live in a user-chosen cloud folder; fall back to app-data.
    if let Some(state) = app.try_state::<AppState>() {
        if let Some(dir) = state.snippets_dir.lock().unwrap().clone() {
            let _ = fs::create_dir_all(&dir);
            return dir.join("snippets.json");
        }
    }
    app_file(app, "snippets.json")
}

fn history_path(app: &tauri::AppHandle) -> PathBuf {
    app_file(app, "clipboard_history.json")
}

fn settings_path(app: &tauri::AppHandle) -> PathBuf {
    app_file(app, "settings.json")
}

// Reads and parses `path`. A missing file yields the default. A file that
// exists but does not parse is moved aside to `*.corrupt.json` and the default
// returned — never silently treated as "empty" and then overwritten.
fn read_json<T: DeserializeOwned + Default>(path: &Path) -> T {
    let Ok(data) = fs::read_to_string(path) else {
        return T::default();
    };
    match serde_json::from_str(&data) {
        Ok(value) => value,
        Err(_) => {
            let _ = fs::rename(path, path.with_extension("corrupt.json"));
            T::default()
        }
    }
}

// Serializes to a temp file, tightens its mode to 0600, then atomically renames
// over the target. A crash or full disk can never leave a half-written file,
// and a serialize failure returns an error instead of clobbering good data.
fn write_json_atomic<T: Serialize>(path: &Path, value: &T) -> std::io::Result<()> {
    let json = serde_json::to_string_pretty(value)
        .map_err(|e| std::io::Error::new(std::io::ErrorKind::InvalidData, e))?;
    let tmp = path.with_extension("json.tmp");
    fs::write(&tmp, json.as_bytes())?;
    #[cfg(unix)]
    {
        fs::set_permissions(&tmp, fs::Permissions::from_mode(0o600))?;
    }
    fs::rename(&tmp, path)
}

fn now_millis() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

