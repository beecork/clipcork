// How often the watcher samples the pasteboard. On macOS this only reads the
// cheap `changeCount`; the text is decoded only when the count actually moved.
const POLL_INTERVAL: Duration = Duration::from_millis(200);

// Copies larger than this are not logged to history. A multi-megabyte paste
// would otherwise be held in memory three times over (Rust state, JS array, DOM)
// and re-serialised on every subsequent copy. It stays on the system clipboard;
// ClipCork just doesn't record it.
const MAX_ENTRY_BYTES: usize = 100_000;

// Monotonic tail for entry ids so two copies in the same millisecond can't
// collide (row click handlers resolve by id).
static ID_COUNTER: AtomicU64 = AtomicU64::new(0);

fn next_id() -> String {
    format!(
        "{}-{}",
        now_millis(),
        ID_COUNTER.fetch_add(1, Ordering::Relaxed)
    )
}

// Gap between the bottom of the menu bar icon and the top of the panel.
const PANEL_GAP: f64 = 6.0;
// Keeps a panel anchored to an icon near the screen edge fully on-screen.
const SCREEN_MARGIN: f64 = 8.0;
// A click on the status item makes it key, so the panel blurs and hides just
// before the tray handler runs. Anything hidden this recently was closed by
// that same click and must not be reopened by it.
const REOPEN_GUARD_MS: u64 = 250;
// Opening over someone else's fullscreen space orders the panel in without
// activating this app, and AppKit can report a blur before key status settles.
// Auto-hiding on that blur makes the panel look like it never opened, so blurs
// this soon after a show are ignored.
const FOCUS_GUARD_MS: u64 = 250;

// macOS pasteboard privacy markers. Password managers (1Password, Keychain,
// Bitwarden, …) stamp copied secrets with ConcealedType precisely so clipboard
// managers skip them; Transient/AutoGenerated mark scratch and machine-produced
// content. Items carrying any of these are never recorded.
#[cfg(target_os = "macos")]
const PRIVATE_PASTEBOARD_TYPES: [&str; 3] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

#[derive(Serialize, Deserialize, Clone)]
struct Snippet {
    id: String,
    title: String,
    content: String,
    tag: String,
    created: u64,
    updated: u64,
    // Usage tracking for "most-used floats up" ordering (managed by the frontend;
    // declared here so Rust-side load/save round-trips don't drop them).
    #[serde(default)]
    uses: u64,
    #[serde(default)]
    last_used: u64,
}

#[derive(Serialize, Deserialize, Clone)]
struct ClipboardEntry {
    id: String,
    text: String,
    timestamp: u64,
    // Pinned entries survive the history cap and sort to the top.
    #[serde(default)]
    pinned: bool,
}

struct AppState {
    clipboard_history: Mutex<Vec<ClipboardEntry>>,
    // The watcher's dedupe key. Shared (not thread-local) so that
    // `clear_clipboard_history` can reset it — otherwise re-copying the text you
    // just cleared would be deduped away and never reappear.
    last_clipboard: Mutex<String>,
    history_limit: Mutex<usize>,
    recording_enabled: Mutex<bool>,
    // The exact text this app just wrote to the clipboard, so the watcher can
    // suppress recording its own write without dropping a genuine user copy that
    // happened to land in the same tick.
    skip_text: Mutex<Option<String>>,
    last_hidden_at: Mutex<u64>,
    // Timestamp of the most recent show, for FOCUS_GUARD_MS.
    last_shown_at: Mutex<u64>,
    // The tray icon's screen rect from its most recent event, so the panel can
    // be anchored under it even when opened from the right-click menu.
    last_tray_rect: Mutex<Option<tauri::Rect>>,
    // Custom snippets folder (for cloud-folder sync), synced from settings.
    snippets_dir: Mutex<Option<PathBuf>>,
}

