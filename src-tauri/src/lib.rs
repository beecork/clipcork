#[cfg(test)]
mod tests {
    use super::*;

    fn scratch_dir(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("clipcork_test_{}_{}", std::process::id(), tag));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn entry(id: &str) -> ClipboardEntry {
        ClipboardEntry {
            id: id.to_string(),
            text: format!("text-{id}"),
            timestamp: 1,
            pinned: false,
        }
    }

    #[test]
    fn write_then_read_roundtrips() {
        let dir = scratch_dir("roundtrip");
        let path = dir.join("clipboard_history.json");
        let data = vec![entry("a"), entry("b")];
        write_json_atomic(&path, &data).unwrap();
        let back: Vec<ClipboardEntry> = read_json(&path);
        assert_eq!(back.len(), 2);
        assert_eq!(back[0].id, "a");
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn missing_file_yields_default_without_side_effects() {
        let dir = scratch_dir("missing");
        let path = dir.join("nope.json");
        let back: Vec<ClipboardEntry> = read_json(&path);
        assert!(back.is_empty());
        assert!(!path.with_extension("corrupt.json").exists());
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn corrupt_file_is_moved_aside_not_treated_as_empty() {
        let dir = scratch_dir("corrupt");
        let path = dir.join("snippets.json");
        fs::write(&path, b"{ this is not valid json").unwrap();
        let back: Vec<Snippet> = read_json(&path);
        assert!(back.is_empty());
        // Original is preserved under *.corrupt.json rather than silently lost.
        assert!(!path.exists());
        assert!(path.with_extension("corrupt.json").exists());
        let _ = fs::remove_dir_all(&dir);
    }

    #[cfg(unix)]
    #[test]
    fn writes_are_owner_only() {
        let dir = scratch_dir("perms");
        let path = dir.join("settings.json");
        write_json_atomic(&path, &Settings::default()).unwrap();
        let mode = fs::metadata(&path).unwrap().permissions().mode() & 0o777;
        assert_eq!(mode, 0o600);
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn push_capped_keeps_newest_and_enforces_limit() {
        let mut history = Vec::new();
        for i in 0..5 {
            push_capped(&mut history, entry(&i.to_string()), 3);
        }
        assert_eq!(history.len(), 3);
        // Newest first, oldest dropped.
        assert_eq!(history[0].id, "4");
        assert_eq!(history[2].id, "2");
    }

    #[test]
    fn pinned_entries_survive_the_cap() {
        let mut history: Vec<ClipboardEntry> = Vec::new();
        let mut pin = entry("pinned");
        pin.pinned = true;
        history.push(pin);
        // Push 3 unpinned with a limit of 2 — one unpinned should be evicted,
        // the pinned one must remain.
        for i in 0..3 {
            push_capped(&mut history, entry(&i.to_string()), 2);
        }
        assert!(history.iter().any(|e| e.id == "pinned"));
        assert_eq!(history.iter().filter(|e| !e.pinned).count(), 2);
    }

    #[test]
    fn settings_default_enables_recording() {
        let s = Settings::default();
        assert!(s.enabled);
        assert_eq!(s.history_limit, 20);
    }
}
